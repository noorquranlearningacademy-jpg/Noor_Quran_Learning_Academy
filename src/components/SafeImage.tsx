import { useState } from 'react';

interface SafeImageProps {
  src: string;
  alt: string;
  className?: string;
}

export function SafeImage({ src, alt, className = '' }: SafeImageProps) {
  const [hasError, setHasError] = useState(false);

  if (hasError) {
    return (
      <div
        role="img"
        aria-label={alt}
        className={`flex flex-col items-center justify-center gap-2 bg-light-surface-container text-light-on-surface-variant p-6 text-center ${className}`}
      >
        <span className="material-symbols-outlined text-headline-lg text-light-primary" aria-hidden="true">
          menu_book
        </span>
        <span className="text-label-sm max-w-xs">{alt}</span>
      </div>
    );
  }

  return (
    <img
      src={src}
      alt={alt}
      referrerPolicy="no-referrer"
      onError={() => setHasError(true)}
      className={className}
    />
  );
}
